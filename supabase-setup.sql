-- Tabel surat untuk bagian "Surat kecil untukmu".
create table if not exists public.teacher_letters (
  id bigint generated by default as identity primary key,
  title text not null check (char_length(trim(title)) between 1 and 100),
  teacher_name text not null default '',
  body text not null check (char_length(trim(body)) between 1 and 3000),
  created_at timestamptz not null default now()
);

create index if not exists teacher_letters_created_at_idx
  on public.teacher_letters (created_at desc, id desc);

alter table public.teacher_letters enable row level security;

