-- Jalankan di Supabase Dashboard > SQL Editor.
-- Role superadmin disimpan di app_metadata, bukan user_metadata, agar pengguna tidak dapat menaikkan role sendiri.

create table if not exists public.site_audio (
  id uuid primary key default gen_random_uuid(),
  title text not null,
  artist text not null default '',
  file_path text not null,
  sort_order integer not null default 0,
  is_active boolean not null default true,
  created_at timestamptz not null default now()
);

alter table public.site_audio enable row level security;

drop policy if exists "Public can read active playlist" on public.site_audio;
create policy "Public can read active playlist"
on public.site_audio for select
to anon, authenticated
using (is_active = true);

drop policy if exists "Superadmin can read all tracks" on public.site_audio;
create policy "Superadmin can read all tracks"
on public.site_audio for select
to authenticated
using ((auth.jwt() -> 'app_metadata' ->> 'role') = 'superadmin');

drop policy if exists "Superadmin can insert tracks" on public.site_audio;
create policy "Superadmin can insert tracks"
on public.site_audio for insert
to authenticated
with check ((auth.jwt() -> 'app_metadata' ->> 'role') = 'superadmin');

drop policy if exists "Superadmin can update tracks" on public.site_audio;
create policy "Superadmin can update tracks"
on public.site_audio for update
to authenticated
using ((auth.jwt() -> 'app_metadata' ->> 'role') = 'superadmin')
with check ((auth.jwt() -> 'app_metadata' ->> 'role') = 'superadmin');

drop policy if exists "Superadmin can delete tracks" on public.site_audio;
create policy "Superadmin can delete tracks"
on public.site_audio for delete
to authenticated
using ((auth.jwt() -> 'app_metadata' ->> 'role') = 'superadmin');

